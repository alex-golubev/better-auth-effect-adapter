import type { BetterAuthOptions } from 'better-auth'
import type { BetterAuthDBSchema, DBFieldAttribute, DBTableIndex } from 'better-auth/db'
import { Array as Arr, Effect, Match, Option, Order, Predicate, pipe } from 'effect'
import type { Dialect } from './dialect'
import { EffectSqlAdapterError } from './errors'

/** How primary keys are produced, derived from `advanced.database.generateId`. */
export type IdStrategy = 'string' | 'serial' | 'uuid'

export interface SchemaConfig {
  readonly dialect: Dialect
  readonly idStrategy: IdStrategy
}

export const idStrategyOf = (options: BetterAuthOptions): IdStrategy =>
  Match.value(options.advanced?.database?.generateId).pipe(
    Match.when('serial', (): IdStrategy => 'serial'),
    Match.when('uuid', (): IdStrategy => 'uuid'),
    Match.orElse((): IdStrategy => 'string'),
  )

type TableDefinition = BetterAuthDBSchema[string]
type OnDelete = NonNullable<NonNullable<DBFieldAttribute['references']>['onDelete']>
type ScalarKind = 'boolean' | 'date' | 'json' | 'string[]' | 'number[]'

interface ForeignKey {
  readonly table: string
  readonly column: string
  readonly onDelete: OnDelete
  readonly toId: boolean
}

interface Column {
  readonly name: string
  readonly field: DBFieldAttribute
  readonly references: Option.Option<ForeignKey>
}

interface Index {
  readonly name: string
  readonly columns: ReadonlyArray<string>
  readonly unique: boolean
}

interface Table {
  readonly name: string
  readonly order: number
  readonly disableMigrations: boolean
  readonly columns: ReadonlyArray<Column>
  readonly indexes: ReadonlyArray<Index>
}

const schemaError = (message: string): EffectSqlAdapterError => new EffectSqlAdapterError({ message })

// ---------------------------------------------------------------------------
// Dialect tables

const quoteChars: Record<Dialect, string> = { sqlite: '"', pg: '"', mysql: '`' }

const idColumnTypes: Record<Dialect, Record<IdStrategy, string>> = {
  sqlite: {
    string: 'text NOT NULL PRIMARY KEY',
    serial: 'integer NOT NULL PRIMARY KEY',
    uuid: 'text NOT NULL PRIMARY KEY',
  },
  pg: {
    string: 'text NOT NULL PRIMARY KEY',
    serial: 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    uuid: 'uuid NOT NULL DEFAULT pg_catalog.gen_random_uuid() PRIMARY KEY',
  },
  mysql: {
    // Custom id generators may produce ids longer than a uuid.
    string: 'varchar(255) NOT NULL PRIMARY KEY',
    serial: 'integer NOT NULL AUTO_INCREMENT PRIMARY KEY',
    uuid: 'varchar(36) NOT NULL PRIMARY KEY',
  },
}

/** Type of a column referencing `id`. */
const foreignKeyIdTypes: Record<Dialect, Record<IdStrategy, string>> = {
  sqlite: { string: 'text', serial: 'integer', uuid: 'text' },
  pg: { string: 'text', serial: 'integer', uuid: 'uuid' },
  mysql: { string: 'varchar(255)', serial: 'integer', uuid: 'varchar(36)' },
}

const scalarTypes: Record<Dialect, Record<ScalarKind, string>> = {
  sqlite: { boolean: 'integer', date: 'date', json: 'text', 'string[]': 'text', 'number[]': 'text' },
  pg: { boolean: 'boolean', date: 'timestamptz', json: 'jsonb', 'string[]': 'jsonb', 'number[]': 'jsonb' },
  // DATETIME rather than TIMESTAMP: TIMESTAMP ends in 2038.
  mysql: { boolean: 'boolean', date: 'datetime(3)', json: 'json', 'string[]': 'json', 'number[]': 'json' },
}

/** Database default for date fields whose better-auth default is a function (`createdAt`, …). */
const timestampDefaults: Record<Dialect, Option.Option<string>> = {
  sqlite: Option.none(),
  pg: Option.some('DEFAULT CURRENT_TIMESTAMP'),
  mysql: Option.some('DEFAULT CURRENT_TIMESTAMP(3)'),
}

const quote =
  (dialect: Dialect) =>
  (identifier: string): string => {
    const char = quoteChars[dialect]
    return `${char}${identifier.replaceAll(char, char + char)}${char}`
  }

// ---------------------------------------------------------------------------
// Index naming. Mirrors better-auth's own migration naming, so schemas from
// here and from `getMigrations` (kysely) use the same index names.

const MAX_INDEX_NAME_BYTES = 63
const INDEX_NAME_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/

const utf8Length = (value: string): number => new TextEncoder().encode(value).length

/** Longest prefix of `value` (by code points) that fits into `maxBytes` UTF-8 bytes. */
const truncateUtf8 = (value: string, maxBytes: number): string =>
  pipe(
    Arr.fromIterable(value),
    Arr.scan('', (prefix, character) => prefix + character),
    Arr.takeWhile((prefix) => utf8Length(prefix) <= maxBytes),
    Arr.last,
    Option.getOrElse(() => ''),
  )

/** 32-bit FNV-1a over UTF-16 code units, as better-auth computes it. */
const stableHash = (value: string): string =>
  pipe(
    Array.from({ length: value.length }, (_, i) => value.charCodeAt(i)),
    Arr.reduce(2166136261, (hash, code) => Math.imul(hash ^ code, 16777619)),
    (hash) => (hash >>> 0).toString(16).padStart(8, '0'),
  )

const generatedIndexName = (table: string, columns: ReadonlyArray<string>, unique: boolean): string => {
  const kind = unique ? 'uidx' : 'idx'
  const name = `${table}_${columns.join('_')}_${kind}`
  const suffix = `_${stableHash(name)}_${kind}`
  return utf8Length(name) <= MAX_INDEX_NAME_BYTES
    ? name
    : `${truncateUtf8(name.slice(0, -kind.length - 1), MAX_INDEX_NAME_BYTES - utf8Length(suffix))}${suffix}`
}

const validIndexName = (name: string): Effect.Effect<string, EffectSqlAdapterError> =>
  Effect.succeed(name).pipe(
    Effect.filterOrFail(
      (value) => INDEX_NAME_PATTERN.test(value),
      () =>
        schemaError(
          `Index name "${name}" must start with a letter or underscore and contain only letters, digits and underscores.`,
        ),
    ),
    Effect.filterOrFail(
      (value) => utf8Length(value) <= MAX_INDEX_NAME_BYTES,
      () => schemaError(`Index name "${name}" must be at most ${MAX_INDEX_NAME_BYTES} bytes.`),
    ),
  )

// ---------------------------------------------------------------------------
// Logical schema → physical tables

const columnName = (fieldName: string, field: DBFieldAttribute): string => field.fieldName || fieldName

const isStringLike = (field: DBFieldAttribute): boolean => field.type === 'string' || Arr.isArray(field.type)

const isIndexable = (field: DBFieldAttribute): boolean =>
  field.type !== 'json' && field.type !== 'string[]' && field.type !== 'number[]'

const resolveIndexColumn =
  (table: string, fields: Record<string, DBFieldAttribute>, unique: boolean) =>
  (fieldName: string): Effect.Effect<string, EffectSqlAdapterError> =>
    pipe(
      Effect.fromNullishOr(fields[fieldName]),
      Effect.mapError(() => schemaError(`Index on table "${table}" references unknown field "${fieldName}".`)),
      Effect.filterOrFail(isIndexable, () =>
        schemaError(`Index on table "${table}" references field "${fieldName}", whose type is not indexable.`),
      ),
      Effect.filterOrFail(
        (field) => !unique || field.required !== false,
        () => schemaError(`Unique index on table "${table}" can only include required fields (got "${fieldName}").`),
      ),
      Effect.map((field) => columnName(fieldName, field)),
    )

const resolveIndex = (
  table: string,
  fields: Record<string, DBFieldAttribute>,
  index: DBTableIndex,
): Effect.Effect<Index, EffectSqlAdapterError> =>
  Effect.gen(function* () {
    const unique = index.unique ?? false
    const columns = yield* Effect.forEach(index.fields, resolveIndexColumn(table, fields, unique))
    const name = yield* pipe(
      Option.fromUndefinedOr(index.name),
      Option.match({
        onNone: () => Effect.succeed(generatedIndexName(table, columns, unique)),
        onSome: validIndexName,
      }),
    )
    return { name, columns, unique }
  })

const resolveReference =
  (schema: BetterAuthDBSchema) =>
  (field: DBFieldAttribute): Option.Option<ForeignKey> =>
    Option.map(Option.fromUndefinedOr(field.references), (reference) => {
      const target = Option.fromUndefinedOr(schema[reference.model])
      const toId = reference.field === 'id'
      return {
        table: pipe(
          target,
          Option.map((definition) => definition.modelName),
          Option.getOrElse(() => reference.model),
        ),
        column: toId
          ? 'id'
          : pipe(
              target,
              Option.flatMap((definition) => Option.fromUndefinedOr(definition.fields[reference.field])),
              Option.map((targetField) => columnName(reference.field, targetField)),
              Option.getOrElse(() => reference.field),
            ),
        onDelete: reference.onDelete ?? 'cascade',
        toId,
      }
    })

/** Several schema keys may share a table name; their fields merge, later ones winning (as in better-auth). */
const buildTable = (
  schema: BetterAuthDBSchema,
  name: string,
  definitions: Arr.NonEmptyReadonlyArray<TableDefinition>,
): Effect.Effect<Table, EffectSqlAdapterError> =>
  Effect.map(
    Effect.all(
      Arr.flatMap(definitions, (definition) =>
        Arr.map(definition.indexes ?? [], (index) => resolveIndex(name, definition.fields, index)),
      ),
    ),
    (indexes) => ({
      name,
      order: definitions[0].order ?? Number.POSITIVE_INFINITY,
      disableMigrations: Arr.some(definitions, (definition) => definition.disableMigrations === true),
      columns: pipe(
        Arr.flatMap(definitions, (definition) => Object.entries(definition.fields)),
        Arr.map(([fieldName, field]): readonly [string, Column] => {
          const column = columnName(fieldName, field)
          return [column, { name: column, field, references: resolveReference(schema)(field) }]
        }),
        (entries) => Object.values(Object.fromEntries(entries)),
      ),
      indexes,
    }),
  )

const buildTables = (schema: BetterAuthDBSchema): Effect.Effect<ReadonlyArray<Table>, EffectSqlAdapterError> =>
  pipe(
    Effect.forEach(
      Object.entries(Arr.groupBy(Object.values(schema), (definition) => definition.modelName)),
      ([name, definitions]) => buildTable(schema, name, definitions),
    ),
    Effect.map(Arr.filter((table) => !table.disableMigrations)),
  )

const byDeclaredOrder: Order.Order<Table> = Order.mapInput(Order.Number, (table: Table) => table.order)

const dependencies = (table: Table): ReadonlyArray<string> =>
  pipe(
    Arr.map(table.columns, ({ references }) => Option.map(references, (foreignKey) => foreignKey.table)),
    Arr.getSomes,
    Arr.filter((name) => name !== table.name),
  )

/** Referenced tables first; otherwise better-auth's declared `order`. */
const sortByDependencies = (tables: ReadonlyArray<Table>): ReadonlyArray<Table> => {
  const names = new Set(Arr.map(tables, (table) => table.name))
  const isReady = (created: ReadonlySet<string>) => (table: Table) =>
    Arr.every(dependencies(table), (name) => !names.has(name) || created.has(name))
  const go = (pending: ReadonlyArray<Table>, created: ReadonlySet<string>): ReadonlyArray<Table> =>
    pipe(
      Arr.findFirst(pending, isReady(created)),
      // A reference cycle cannot be ordered; fall back to the declared order.
      Option.orElse(() => Arr.head(pending)),
      Option.match({
        onNone: () => [],
        onSome: (next) => [
          next,
          ...go(
            Arr.filter(pending, (table) => table !== next),
            new Set([...created, next.name]),
          ),
        ],
      }),
    )
  return go(Arr.sort(tables, byDeclaredOrder), new Set())
}

