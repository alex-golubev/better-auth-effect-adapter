// Column types

const MYSQL_INDEX_KEY_BYTES = 3072
const MYSQL_BYTES_PER_CHAR = 4
const MYSQL_INDEXED_STRING_LENGTH = 191

/**
 * MySQL can't index TEXT without a prefix length, so strings in table indexes
 * become VARCHAR sized to fit InnoDB's index key limit (utf8mb4).
 */
const mysqlIndexedStringLength = (table: Table, column: string): Option.Option<number> => {
  const isStringColumn = (name: string) =>
    Arr.some(table.columns, (candidate) => candidate.name === name && isStringLike(candidate.field))
  return pipe(
    Arr.filter(table.indexes, (index) => index.columns.includes(column)),
    Option.liftPredicate(Arr.isReadonlyArrayNonEmpty),
    Option.map(
      Arr.reduce(MYSQL_INDEXED_STRING_LENGTH, (length, index) => {
        const strings = Arr.filter(index.columns, isStringColumn).length
        const otherBytes = (index.columns.length - strings) * 16
        return strings === 0
          ? length
          : Math.min(
              length,
              Math.floor(Math.max(1, MYSQL_INDEX_KEY_BYTES - otherBytes) / MYSQL_BYTES_PER_CHAR / strings),
            )
      }),
    ),
  )
}

const stringType = (dialect: Dialect, table: Table, column: Column): string =>
  dialect === 'mysql'
    ? pipe(
        mysqlIndexedStringLength(table, column.name),
        Option.map((length) => `varchar(${length})`),
        Option.getOrElse(() =>
          column.field.unique || column.field.index || column.field.sortable || Option.isSome(column.references)
            ? 'varchar(255)'
            : 'text',
        ),
      )
    : 'text'

const columnType = (
  { dialect, idStrategy }: SchemaConfig,
  table: Table,
  column: Column,
): Effect.Effect<string, EffectSqlAdapterError> =>
  Option.exists(column.references, (foreignKey) => foreignKey.toId)
    ? Effect.succeed(foreignKeyIdTypes[dialect][idStrategy])
    : pipe(
        Match.value(column.field.type),
        Match.when('string', () => stringType(dialect, table, column)),
        Match.when(Arr.isArray, () => stringType(dialect, table, column)),
        Match.when('number', () => (column.field.bigint ? 'bigint' : 'integer')),
        Match.when(Match.is('boolean', 'date', 'json', 'string[]', 'number[]'), (kind) => scalarTypes[dialect][kind]),
        Match.option,
        Effect.fromOption,
        Effect.mapError(() =>
          schemaError(
            `Unsupported type ${JSON.stringify(column.field.type)} for column "${table.name}.${column.name}".`,
          ),
        ),
      )

// ---------------------------------------------------------------------------
// Rendering

const columnDefinition = (
  config: SchemaConfig,
  table: Table,
  column: Column,
): Effect.Effect<string, EffectSqlAdapterError> =>
  Effect.map(columnType(config, table, column), (type) =>
    [
      quote(config.dialect)(column.name),
      type,
      column.field.required !== false && 'NOT NULL',
      column.field.unique === true && 'UNIQUE',
      ...pipe(
        timestampDefaults[config.dialect],
        Option.filter(() => column.field.type === 'date' && Predicate.isFunction(column.field.defaultValue)),
        Option.toArray,
      ),
    ]
      .filter(Predicate.isString)
      .join(' '),
  )

const foreignKeyDefinition = (dialect: Dialect, column: string, foreignKey: ForeignKey): string => {
  const q = quote(dialect)
  return `FOREIGN KEY (${q(column)}) REFERENCES ${q(foreignKey.table)} (${q(foreignKey.column)}) ON DELETE ${foreignKey.onDelete.toUpperCase()}`
}

const createTable = (config: SchemaConfig, table: Table): Effect.Effect<string, EffectSqlAdapterError> => {
  const q = quote(config.dialect)
  const columns = Arr.filter(table.columns, (column) => column.name !== 'id')
  return Effect.map(
    Effect.forEach(columns, (column) => columnDefinition(config, table, column)),
    (definitions) => {
      const lines = [
        `${q('id')} ${idColumnTypes[config.dialect][config.idStrategy]}`,
        ...definitions,
        ...Arr.getSomes(
          Arr.map(columns, (column) =>
            Option.map(column.references, (foreignKey) =>
              foreignKeyDefinition(config.dialect, column.name, foreignKey),
            ),
          ),
        ),
      ]
      return `CREATE TABLE ${q(table.name)} (\n  ${lines.join(',\n  ')}\n)`
    },
  )
}

/** Plain indexes declared on a field (`index: true`); unique fields get an inline UNIQUE instead. */
const fieldIndexes = (table: Table): ReadonlyArray<Index> =>
  pipe(
    Arr.filter(table.columns, ({ field }) => field.index === true && field.unique !== true),
    Arr.map(({ name }) => ({ name: generatedIndexName(table.name, [name], false), columns: [name], unique: false })),
  )

const createIndex = (dialect: Dialect, table: string, index: Index): string => {
  const q = quote(dialect)
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${q(index.name)} ON ${q(table)} (${Arr.map(index.columns, q).join(', ')})`
}

/**
 * The DDL statements that create every table of a better-auth schema (as returned
 * by `getAuthTables(options)`), referenced tables first, followed by their indexes.
 */
export const schemaStatements = (
  schema: BetterAuthDBSchema,
  config: SchemaConfig,
): Effect.Effect<ReadonlyArray<string>, EffectSqlAdapterError> =>
  Effect.gen(function* () {
    const tables = sortByDependencies(yield* buildTables(schema))
    const createTables = yield* Effect.forEach(tables, (table) => createTable(config, table))
    const createIndexes = Arr.flatMap(tables, (table) =>
      Arr.map([...fieldIndexes(table), ...table.indexes], (index) => createIndex(config.dialect, table.name, index)),
    )
    return [...createTables, ...createIndexes]
  })

/** Joins statements into a single SQL script. */
export const renderSchema = (statements: ReadonlyArray<string>): string =>
  Arr.match(statements, {
    onEmpty: () => '',
    onNonEmpty: (nonEmpty) => `${nonEmpty.join(';\n\n')};\n`,
  })
