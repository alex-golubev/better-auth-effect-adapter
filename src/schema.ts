import type { BetterAuthOptions } from 'better-auth'
import type { BetterAuthDBSchema, DBFieldAttribute, DBTableIndex } from 'better-auth/db'
import { Array as Arr, Effect, identity, Match, Option, Order, Predicate, pipe, Record } from 'effect'
import type { SqlClient } from 'effect/sql'
import type { Dialect } from './dialect'
import { adapterError, type EffectSqlAdapterError } from './errors'

export type IdStrategy = 'string' | 'serial' | 'uuid'

export interface SchemaConfig {
  readonly dialect: Dialect
  readonly idStrategy: IdStrategy
  /** The adapter passes `clientNames`; identity by default. */
  readonly rename?: (name: string) => string
}

export const idStrategyOf = (options: BetterAuthOptions): IdStrategy =>
  Match.value(options.advanced?.database?.generateId).pipe(
    Match.when('serial', (): IdStrategy => 'serial'),
    Match.when('uuid', (): IdStrategy => 'uuid'),
    Match.orElse((): IdStrategy => 'string'),
  )

type TableDefinition = BetterAuthDBSchema[string]
type OnDelete = NonNullable<NonNullable<DBFieldAttribute['references']>['onDelete']>
type ScalarKind = 'boolean' | 'date' | 'json' | 'string[]' | 'number[]'

interface ForeignKey {
  readonly table: string
  readonly column: string
  readonly onDelete: OnDelete
  readonly toId: boolean
}

interface Column {
  readonly name: string
  readonly field: DBFieldAttribute
  readonly references: Option.Option<ForeignKey>
}

interface Index {
  readonly name: string
  readonly columns: ReadonlyArray<string>
  readonly unique: boolean
}

interface Table {
  readonly name: string
  readonly order: number
  readonly disableMigrations: boolean
  readonly columns: ReadonlyArray<Column>
  readonly indexes: ReadonlyArray<Index>
}

const quoteChars: Record<Dialect, string> = { sqlite: '"', pg: '"', mysql: '`' }

const idColumnTypes: Record<Dialect, Record<IdStrategy, string>> = {
  sqlite: {
    string: 'text NOT NULL PRIMARY KEY',
    serial: 'integer NOT NULL PRIMARY KEY',
    uuid: 'text NOT NULL PRIMARY KEY',
  },
  pg: {
    string: 'text NOT NULL PRIMARY KEY',
    serial: 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    uuid: 'uuid NOT NULL DEFAULT pg_catalog.gen_random_uuid() PRIMARY KEY',
  },
  mysql: {
    // Custom id generators may produce ids longer than a uuid.
    string: 'varchar(255) NOT NULL PRIMARY KEY',
    serial: 'integer NOT NULL AUTO_INCREMENT PRIMARY KEY',
    uuid: 'varchar(36) NOT NULL PRIMARY KEY',
  },
}

const scalarTypes: Record<Dialect, Record<ScalarKind, string>> = {
  sqlite: { boolean: 'integer', date: 'date', json: 'text', 'string[]': 'text', 'number[]': 'text' },
  pg: { boolean: 'boolean', date: 'timestamptz', json: 'jsonb', 'string[]': 'jsonb', 'number[]': 'jsonb' },
  // DATETIME rather than TIMESTAMP: TIMESTAMP ends in 2038.
  mysql: { boolean: 'boolean', date: 'datetime(3)', json: 'json', 'string[]': 'json', 'number[]': 'json' },
}

/** Like better-auth's migrations, for dates with a function default (`createdAt`, …). */
const timestampDefaults: Record<Dialect, Option.Option<string>> = {
  sqlite: Option.none(),
  pg: Option.some('DEFAULT CURRENT_TIMESTAMP'),
  mysql: Option.some('DEFAULT CURRENT_TIMESTAMP(3)'),
}

const quote =
  (dialect: Dialect) =>
  (identifier: string): string => {
    const char = quoteChars[dialect]
    return `${char}${identifier.replaceAll(char, char + char)}${char}`
  }

const unquote =
  (dialect: Dialect) =>
  (quoted: string): string => {
    const char = quoteChars[dialect]
    return quoted.slice(1, -1).replaceAll(char + char, char)
  }

/** Names as the client's queries render them. SqlClient doesn't expose `transformQueryNames`, hence the compile. */
export const clientNames =
  (sql: SqlClient.SqlClient, dialect: Dialect) =>
  (name: string): string =>
    unquote(dialect)(sql`${sql(name)}`.compile()[0])

const MAX_INDEX_NAME_BYTES = 63
const INDEX_NAME_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/

const utf8Length = (value: string): number => new TextEncoder().encode(value).length

const truncateUtf8 = (value: string, maxBytes: number): string =>
  pipe(
    Arr.fromIterable(value),
    Arr.scan('', (prefix, character) => prefix + character),
    Arr.takeWhile((prefix) => utf8Length(prefix) <= maxBytes),
    Arr.last,
    Option.getOrElse(() => ''),
  )

/** 32-bit FNV-1a over UTF-16 code units, as better-auth computes it. */
const stableHash = (value: string): string =>
  pipe(
    Array.from({ length: value.length }, (_, i) => value.charCodeAt(i)),
    Arr.reduce(2166136261, (hash, code) => Math.imul(hash ^ code, 16777619)),
    (hash) => (hash >>> 0).toString(16).padStart(8, '0'),
  )

/** Same names as better-auth's own migrations. */
const generatedIndexName = (table: string, columns: ReadonlyArray<string>, unique: boolean): string => {
  const kind = unique ? 'uidx' : 'idx'
  const name = `${table}_${columns.join('_')}_${kind}`
  const suffix = `_${stableHash(name)}_${kind}`
  return utf8Length(name) <= MAX_INDEX_NAME_BYTES
    ? name
    : `${truncateUtf8(name.slice(0, -kind.length - 1), MAX_INDEX_NAME_BYTES - utf8Length(suffix))}${suffix}`
}

const validIndexName = (name: string): Effect.Effect<string, EffectSqlAdapterError> =>
  Effect.succeed(name).pipe(
    Effect.filterOrFail(
      (value) => INDEX_NAME_PATTERN.test(value),
      () =>
        adapterError(
          `Index name "${name}" must start with a letter or underscore and contain only letters, digits and underscores.`,
        ),
    ),
    Effect.filterOrFail(
      (value) => utf8Length(value) <= MAX_INDEX_NAME_BYTES,
      () => adapterError(`Index name "${name}" must be at most ${MAX_INDEX_NAME_BYTES} bytes.`),
    ),
  )

const columnName = (fieldName: string, field: DBFieldAttribute): string => field.fieldName || fieldName

const isStringLike = (field: DBFieldAttribute): boolean => field.type === 'string' || Arr.isArray(field.type)

const isIndexable = (field: DBFieldAttribute): boolean =>
  field.type !== 'json' && field.type !== 'string[]' && field.type !== 'number[]'

const resolveIndexColumn =
  (table: string, fields: Record<string, DBFieldAttribute>, unique: boolean) =>
  (fieldName: string): Effect.Effect<string, EffectSqlAdapterError> =>
    pipe(
      Effect.fromNullishOr(fields[fieldName]),
      Effect.mapError(() => adapterError(`Index on table "${table}" references unknown field "${fieldName}".`)),
      Effect.filterOrFail(isIndexable, () =>
        adapterError(`Index on table "${table}" references field "${fieldName}", whose type is not indexable.`),
      ),
      Effect.filterOrFail(
        (field) => !unique || field.required !== false,
        () => adapterError(`Unique index on table "${table}" can only include required fields (got "${fieldName}").`),
      ),
      Effect.map((field) => columnName(fieldName, field)),
    )

const resolveIndex = (
  table: string,
  fields: Record<string, DBFieldAttribute>,
  index: DBTableIndex,
): Effect.Effect<Index, EffectSqlAdapterError> =>
  Effect.gen(function* () {
    const unique = index.unique ?? false
    const columns = yield* Effect.forEach(index.fields, resolveIndexColumn(table, fields, unique))
    const name = yield* pipe(
      Option.fromUndefinedOr(index.name),
      Option.match({
        onNone: () => Effect.succeed(generatedIndexName(table, columns, unique)),
        onSome: validIndexName,
      }),
    )
    return { name, columns, unique }
  })

const resolveReference =
  (schema: BetterAuthDBSchema, rename: (name: string) => string) =>
  (field: DBFieldAttribute): Option.Option<ForeignKey> =>
    Option.map(Option.fromUndefinedOr(field.references), (reference) => {
      const target = Option.fromUndefinedOr(schema[reference.model])
      const toId = reference.field === 'id'
      return {
        table: pipe(
          target,
          Option.map((definition) => definition.modelName),
          Option.getOrElse(() => rename(reference.model)),
        ),
        column: toId
          ? rename('id')
          : pipe(
              target,
              Option.flatMap((definition) => Option.fromUndefinedOr(definition.fields[reference.field])),
              Option.map((targetField) => columnName(reference.field, targetField)),
              Option.getOrElse(() => rename(reference.field)),
            ),
        onDelete: reference.onDelete ?? 'cascade',
        toId,
      }
    })

/** Schema keys sharing a table merge their fields, later ones winning, as in better-auth. */
const buildTable = (
  schema: BetterAuthDBSchema,
  rename: (name: string) => string,
  name: string,
  definitions: Arr.NonEmptyReadonlyArray<TableDefinition>,
): Effect.Effect<Table, EffectSqlAdapterError> =>
  Effect.map(
    Effect.all(
      Arr.flatMap(definitions, (definition) =>
        Arr.map(definition.indexes ?? [], (index) => resolveIndex(name, definition.fields, index)),
      ),
    ),
    (indexes) => ({
      name,
      order: definitions[0].order ?? Number.POSITIVE_INFINITY,
      disableMigrations: Arr.some(definitions, (definition) => definition.disableMigrations === true),
      columns: pipe(
        Arr.flatMap(definitions, (definition) => Object.entries(definition.fields)),
        Arr.map(([fieldName, field]): readonly [string, Column] => {
          const column = columnName(fieldName, field)
          return [column, { name: column, field, references: resolveReference(schema, rename)(field) }]
        }),
        (entries) => Object.values(Object.fromEntries(entries)),
      ),
      indexes,
    }),
  )

/** Up front, so index names come from physical names. */
const renameSchema = (schema: BetterAuthDBSchema, rename: (name: string) => string): BetterAuthDBSchema =>
  Record.map(schema, (definition) => ({
    ...definition,
    modelName: rename(definition.modelName),
    fields: Record.map(definition.fields, (field, key) => ({ ...field, fieldName: rename(columnName(key, field)) })),
  }))

const buildTables = (
  schema: BetterAuthDBSchema,
  rename: (name: string) => string,
): Effect.Effect<ReadonlyArray<Table>, EffectSqlAdapterError> =>
  pipe(
    Effect.forEach(
      Object.entries(Arr.groupBy(Object.values(schema), (definition) => definition.modelName)),
      ([name, definitions]) => buildTable(schema, rename, name, definitions),
    ),
    Effect.map(Arr.filter((table) => !table.disableMigrations)),
  )

const byDeclaredOrder: Order.Order<Table> = Order.mapInput(Order.Number, (table: Table) => table.order)

const dependencies = (table: Table): ReadonlyArray<string> =>
  pipe(
    Arr.map(table.columns, ({ references }) => Option.map(references, (foreignKey) => foreignKey.table)),
    Arr.getSomes,
    Arr.filter((name) => name !== table.name),
  )

const sortByDependencies = (tables: ReadonlyArray<Table>): ReadonlyArray<Table> => {
  const names = new Set(Arr.map(tables, (table) => table.name))
  const isReady = (created: ReadonlySet<string>) => (table: Table) =>
    Arr.every(dependencies(table), (name) => !names.has(name) || created.has(name))
  const go = (pending: ReadonlyArray<Table>, created: ReadonlySet<string>): ReadonlyArray<Table> =>
    pipe(
      Arr.findFirst(pending, isReady(created)),
      // A reference cycle can't be ordered: keep the declared order.
      Option.orElse(() => Arr.head(pending)),
      Option.match({
        onNone: () => [],
        onSome: (next) => [
          next,
          ...go(
            Arr.filter(pending, (table) => table !== next),
            new Set([...created, next.name]),
          ),
        ],
      }),
    )
  return go(Arr.sort(tables, byDeclaredOrder), new Set())
}

const MYSQL_INDEX_KEY_BYTES = 3072
const MYSQL_BYTES_PER_CHAR = 4
const MYSQL_INDEXED_STRING_LENGTH = 191

/** MySQL can't index TEXT without a prefix: indexed strings become VARCHAR within InnoDB's key limit. */
const mysqlIndexedStringLength = (table: Table, column: string): Option.Option<number> => {
  const isStringColumn = (name: string) =>
    Arr.some(table.columns, (candidate) => candidate.name === name && isStringLike(candidate.field))
  return pipe(
    Arr.filter(table.indexes, (index) => index.columns.includes(column)),
    Option.liftPredicate(Arr.isReadonlyArrayNonEmpty),
    Option.map(
      Arr.reduce(MYSQL_INDEXED_STRING_LENGTH, (length, index) => {
        const strings = Arr.filter(index.columns, isStringColumn).length
        const otherBytes = (index.columns.length - strings) * 16
        return strings === 0
          ? length
          : Math.min(
              length,
              Math.floor(Math.max(1, MYSQL_INDEX_KEY_BYTES - otherBytes) / MYSQL_BYTES_PER_CHAR / strings),
            )
      }),
    ),
  )
}

type ColumnType = (table: Table, column: Column) => string

const mysqlStringType: ColumnType = (table, column) =>
  pipe(
    mysqlIndexedStringLength(table, column.name),
    Option.map((length) => `varchar(${length})`),
    Option.getOrElse(() =>
      column.field.unique || column.field.index || column.field.sortable || Option.isSome(column.references)
        ? 'varchar(255)'
        : 'text',
    ),
  )

const stringTypes: Record<Dialect, ColumnType> = { sqlite: () => 'text', pg: () => 'text', mysql: mysqlStringType }

/** MySQL string ids get the index key budget too: an index over several of them must still fit. */
const foreignKeyIdTypes: Record<Dialect, Record<IdStrategy, ColumnType>> = {
  sqlite: { string: () => 'text', serial: () => 'integer', uuid: () => 'text' },
  pg: { string: () => 'text', serial: () => 'integer', uuid: () => 'uuid' },
  mysql: { string: mysqlStringType, serial: () => 'integer', uuid: () => 'varchar(36)' },
}

const columnType = (
  { dialect, idStrategy }: SchemaConfig,
  table: Table,
  column: Column,
): Effect.Effect<string, EffectSqlAdapterError> =>
  Option.exists(column.references, (foreignKey) => foreignKey.toId)
    ? Effect.succeed(foreignKeyIdTypes[dialect][idStrategy](table, column))
    : pipe(
        Match.value(column.field.type),
        Match.when('string', () => stringTypes[dialect](table, column)),
        Match.when(Arr.isArray, () => stringTypes[dialect](table, column)),
        Match.when('number', () => (column.field.bigint ? 'bigint' : 'integer')),
        Match.when(Match.is('boolean', 'date', 'json', 'string[]', 'number[]'), (kind) => scalarTypes[dialect][kind]),
        Match.option,
        Effect.fromOption,
        Effect.mapError(() =>
          adapterError(
            `Unsupported type ${JSON.stringify(column.field.type)} for column "${table.name}.${column.name}".`,
          ),
        ),
      )

const columnDefinition = (
  config: SchemaConfig,
  table: Table,
  column: Column,
): Effect.Effect<string, EffectSqlAdapterError> =>
  Effect.map(columnType(config, table, column), (type) =>
    [
      quote(config.dialect)(column.name),
      type,
      column.field.required !== false && 'NOT NULL',
      column.field.unique === true && 'UNIQUE',
      ...pipe(
        timestampDefaults[config.dialect],
        Option.filter(() => column.field.type === 'date' && Predicate.isFunction(column.field.defaultValue)),
        Option.toArray,
      ),
    ]
      .filter(Predicate.isString)
      .join(' '),
  )

const foreignKeyDefinition = (dialect: Dialect, column: string, foreignKey: ForeignKey): string => {
  const q = quote(dialect)
  return `FOREIGN KEY (${q(column)}) REFERENCES ${q(foreignKey.table)} (${q(foreignKey.column)}) ON DELETE ${foreignKey.onDelete.toUpperCase()}`
}

const createTable = (config: SchemaConfig, table: Table): Effect.Effect<string, EffectSqlAdapterError> => {
  const q = quote(config.dialect)
  const id = (config.rename ?? identity)('id')
  const columns = Arr.filter(table.columns, (column) => column.name !== id)
  return Effect.map(
    Effect.forEach(columns, (column) => columnDefinition(config, table, column)),
    (definitions) => {
      const lines = [
        `${q(id)} ${idColumnTypes[config.dialect][config.idStrategy]}`,
        ...definitions,
        ...Arr.getSomes(
          Arr.map(columns, (column) =>
            Option.map(column.references, (foreignKey) =>
              foreignKeyDefinition(config.dialect, column.name, foreignKey),
            ),
          ),
        ),
      ]
      return `CREATE TABLE ${q(table.name)} (\n  ${lines.join(',\n  ')}\n)`
    },
  )
}

/** Unique fields get an inline UNIQUE instead. */
const fieldIndexes = (table: Table): ReadonlyArray<Index> =>
  pipe(
    Arr.filter(table.columns, ({ field }) => field.index === true && field.unique !== true),
    Arr.map(({ name }) => ({ name: generatedIndexName(table.name, [name], false), columns: [name], unique: false })),
  )

const createIndex = (dialect: Dialect, table: string, index: Index): string => {
  const q = quote(dialect)
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${q(index.name)} ON ${q(table)} (${Arr.map(index.columns, q).join(', ')})`
}

export const schemaStatements = (
  schema: BetterAuthDBSchema,
  config: SchemaConfig,
): Effect.Effect<ReadonlyArray<string>, EffectSqlAdapterError> =>
  Effect.gen(function* () {
    const rename = config.rename ?? identity
    const tables = sortByDependencies(yield* buildTables(renameSchema(schema, rename), rename))
    const createTables = yield* Effect.forEach(tables, (table) => createTable(config, table))
    const createIndexes = Arr.flatMap(tables, (table) =>
      Arr.map([...fieldIndexes(table), ...table.indexes], (index) => createIndex(config.dialect, table.name, index)),
    )
    return [...createTables, ...createIndexes]
  })

export const renderSchema = (statements: ReadonlyArray<string>): string =>
  Arr.match(statements, {
    onEmpty: () => '',
    onNonEmpty: (nonEmpty) => `${nonEmpty.join(';\n\n')};\n`,
  })
